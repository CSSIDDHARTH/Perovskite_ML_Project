export function exportCandidatesToCsv(candidates: ConsensusCandidate[]): string {
  const headers = [
    'Rank',
    'ID',
    'Architecture',
    'Perovskite Composition',
    'Annealing Temp (°C)',
    'Annealing Time (min)',
    'Layer Thickness (nm)',
    'ETL Recipe',
    'HTL Recipe',
    'Substrate',
    'Predicted PCE (%)',
    '90% Conformal Lower (%)',
    '90% Conformal Upper (%)',
    'Voc (V)',
    'Jsc (mA/cm2)',
    'FF (%)',
    'Support Percentile',
    'Gower Distance',
    'Lab Feasibility',
    'Synthesis Notes',
  ];

  const rows = candidates.map((c) => [
    c.rank,
    c.id,
    c.architecture,
    `"${c.composition.replace(/"/g, '""')}"`,
    c.annealTemp,
    c.annealTime,
    c.layerThickness,
    `"${c.etlRecipe}"`,
    `"${c.htlRecipe}"`,
    `"${c.substrate}"`,
    c.predictedPce,
    c.conformalLower,
    c.conformalUpper,
    c.voc,
    c.jsc,
    c.ff,
    c.supportPercentile,
    c.gowerDistance,
    `"${c.labFeasibility}"`,
    `"${c.synthesisNotes.replace(/"/g, '""')}"`,
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}
